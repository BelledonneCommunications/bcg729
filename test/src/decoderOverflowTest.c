static int16_t outputSignal[LEAD_SAMPLES+TONE_SAMPLES];

/* the level in dBFS of the tone in one second of the output */
static double toneLevel(const int16_t *signal)
{
	double real = 0.0, imaginary = 0.0;
	int i;
	for (i=0; i<SAMPLE_RATE; i++) {
		real += signal[i]*cos(2.0*PI*TONE_FREQUENCY*i/SAMPLE_RATE);
		imaginary -= signal[i]*sin(2.0*PI*TONE_FREQUENCY*i/SAMPLE_RATE);
	}
	return 20.0*log10(sqrt(real*real + imaginary*imaginary)*2.0/SAMPLE_RATE/32767.0 + 1e-12);
}

int main(void)
{
	bcg729DecoderChannelContextStruct *decoderChannelContext = initBcg729DecoderChannel();
	const int16_t *secondSecond = &(outputSignal[LEAD_SAMPLES+SAMPLE_RATE]); /* the tone has settled after its first second */
	double level;
	int clippedSamples = 0;
	int i;

	for (i=0; i<LEAD_SAMPLES+TONE_SAMPLES; i+=FRAME_LENGTH) {
		bcg729Decoder(decoderChannelContext, &(bitStream[i/FRAME_LENGTH*FRAME_BYTES]), FRAME_BYTES, 0, 0, 0, &(outputSignal[i]));
	}
	closeBcg729DecoderChannel(decoderChannelContext);

	level = toneLevel(secondSecond);
	for (i=0; i<SAMPLE_RATE; i++) {
		if (secondSecond[i] >= 32767 || secondSecond[i] <= -32768) {
			clippedSamples++;
		}
	}
	printf("second second of the %.0f Hz tone: %.1f dBFS (%.1f dBFS in), %d clipped samples\n", TONE_FREQUENCY, level, TONE_LEVEL, clippedSamples);

	if (fabs(level - TONE_LEVEL) > LEVEL_TOLERANCE || clippedSamples > 0) {
		printf("FAIL: the decoder does not recover from the overflow of its LP synthesis filter\n");
		return EXIT_FAILURE;
	}
	printf("OK\n");
	return EXIT_SUCCESS;
}
